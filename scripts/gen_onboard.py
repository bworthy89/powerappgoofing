"""Generate scrOnboard.pa.yaml - the new-customer wizard.

One screen, three steps driven by varWizStep. Each step writes as it goes
rather than holding everything until the end:

  1  customer  -> Patch TB_Customers, keep the created record in varWizCust
  2  solutions -> Patch TB_Installations with Parent blank
  3  units     -> Patch TB_Installations with Parent set to a step-2 solution

Writing at each step is deliberate. Steps 2 and 3 need real rows: step 3's
solution picker is a Choices() dropdown scoped to rows that must already exist,
and Patch needs a real Customer Id. Holding it all in memory would also lose
everything on a refresh. The cost is that abandoning midway leaves a customer
with no equipment, and there is no delete to clean that up.

Installation titles are composed as "<customer> - <product>", matching the
seed convention (e.g. "Northgate Retail Group - CI 300X"), so there is no
title to type.

Controls follow the same rules as the admin form: no Form/DataCard (their
properties cannot be verified), and lookup dropdowns use Choices() because
Classic/DropDown.Value is rejected by the compiler. See app/00_Setup.md.
"""
import io

def prop(o, k, v, ind):
    # A Power Fx value containing ": " terminates the YAML key when written
    # inline, and the parse error then surfaces hundreds of lines away as
    # "mapping values are not allowed here". Emit those as block scalars.
    # See scripts/testdata/bad_inline_colon.pa.yaml.
    if ": " in v:
        o.write(f"{ind}{k}: |\n{ind}  ={v}\n")
    else:
        o.write(f"{ind}{k}: ={v}\n")
def blk(o, k, lines, ind):
    o.write(f"{ind}{k}: |\n")
    for i, l in enumerate(lines):
        o.write(f"{ind}  {'=' if i == 0 else ''}{l}\n")
def ctrl(o, name, control, ind, variant=None):
    o.write(f"{ind}- {name}:\n{ind}    Control: {control}\n")
    if variant: o.write(f"{ind}    Variant: {variant}\n")
    o.write(f"{ind}    Properties:\n")
    return ind + "      "

