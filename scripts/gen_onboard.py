def caption(name, text, y, vis):
    q = ctrl(o, name, "Label", c)
    for k, v in [("Text",f'"{text}"'),("Color","AppTheme.Muted"),
                 ("Font","AppFont"),("Size","AppType.Micro"),
                 ("FontWeight","FontWeight.Semibold"),("Wrap","false"),
                 ("AutoHeight","false"),("Height","16"),
                 ("Width","ContentWidth - (Gutter * 2)"),("X","Gutter"),
                 ("Y",str(y)),("Visible",vis)]: prop(o, k, v, q)

def textin(name, y, vis, multiline=False, default='""'):
    h = 64 if multiline else 40
    q = ctrl(o, name, "Classic/TextInput", c)
    for k, v in [("Default",default),
                 ("Mode","TextMode.MultiLine" if multiline else "TextMode.SingleLine"),
                 ("HintText",'""'),("Height",str(h)),
                 ("Width","ContentWidth - (Gutter * 2)"),("X","Gutter"),
                 ("Y",str(y)),("Visible",vis)] + FIELD + RADIUS: prop(o, k, v, q)
    return h

def dropdown(name, items, y, vis):
    q = ctrl(o, name, "Classic/DropDown", c)
    o.write(f"{q}Items: |\n{q}  ={items}\n")
    for k, v in [("Default",'""'),("AllowEmptySelection","true"),
                 ("Height","40"),("Width","ContentWidth - (Gutter * 2)"),
                 ("X","Gutter"),("Y",str(y)),("Visible",vis)] + FIELD: prop(o, k, v, q)

